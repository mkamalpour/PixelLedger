-- Reference schema for PostgreSQL. Runtime uses SQLite plus the Python business engine.
-- Creates only the dedicated pixelledger namespace; never drops public tables.
BEGIN;
CREATE SCHEMA IF NOT EXISTS pixelledger;
SET LOCAL search_path TO pixelledger;
CREATE TABLE IF NOT EXISTS metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS suppliers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS employees (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
 tier TEXT NOT NULL DEFAULT 'Regular' CHECK(tier IN ('Regular','VIP','Premium','Guest')));
CREATE TABLE IF NOT EXISTS products (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, sku TEXT NOT NULL UNIQUE,
 category TEXT NOT NULL, supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
 price_cents BIGINT NOT NULL CHECK(price_cents>0), base_price_cents BIGINT NOT NULL CHECK(base_price_cents>0),
 cost_cents BIGINT NOT NULL CHECK(cost_cents>=0), stock BIGINT NOT NULL CHECK(stock>=0),
 reorder_point BIGINT NOT NULL DEFAULT 5 CHECK(reorder_point>=0), demand REAL NOT NULL CHECK(demand>0));
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id BIGINT NOT NULL REFERENCES customers(id),
 status TEXT NOT NULL CHECK(status IN ('Pending','Processing','Shipped','Delivered','Cancelled')),
 payment_status TEXT NOT NULL CHECK(payment_status IN ('Unpaid','Failed','Paid','Partial refund','Refunded')),
 total_cents BIGINT NOT NULL CHECK(total_cents>0), created_day BIGINT NOT NULL,
 ship_day BIGINT, delivery_day BIGINT);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 product_id BIGINT NOT NULL REFERENCES products(id), product_name TEXT NOT NULL,
 quantity BIGINT NOT NULL CHECK(quantity>0), unit_price_cents BIGINT NOT NULL CHECK(unit_price_cents>0),
 cost_cents BIGINT NOT NULL CHECK(cost_cents>=0), discount_bps BIGINT NOT NULL CHECK(discount_bps BETWEEN 0 AND 2500),
 tax_cents BIGINT NOT NULL CHECK(tax_cents>=0), total_cents BIGINT NOT NULL CHECK(total_cents>0),
 returned_qty BIGINT NOT NULL DEFAULT 0 CHECK(returned_qty BETWEEN 0 AND quantity),
 refunded_cents BIGINT NOT NULL DEFAULT 0 CHECK(refunded_cents BETWEEN 0 AND total_cents));
CREATE TABLE IF NOT EXISTS payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL REFERENCES orders(id),
 day BIGINT NOT NULL, kind TEXT NOT NULL CHECK(kind IN ('capture','failed','refund')),
 amount_cents BIGINT NOT NULL CHECK(amount_cents>=0), net_sales_cents BIGINT NOT NULL DEFAULT 0);
CREATE UNIQUE INDEX IF NOT EXISTS one_capture_per_order ON payments(order_id) WHERE kind='capture';
CREATE TABLE IF NOT EXISTS "returns" (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, line_id BIGINT NOT NULL REFERENCES order_items(id),
 day BIGINT NOT NULL, quantity BIGINT NOT NULL CHECK(quantity>0), refund_cents BIGINT NOT NULL CHECK(refund_cents>0),
 restock BIGINT NOT NULL CHECK(restock IN (0,1)), reason TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS inventory_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_id BIGINT NOT NULL REFERENCES products(id),
 day BIGINT NOT NULL, change_amount BIGINT NOT NULL, reason TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ledger (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, day BIGINT NOT NULL, kind TEXT NOT NULL,
 amount_cents BIGINT NOT NULL, description TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, day BIGINT NOT NULL, kind TEXT NOT NULL, message TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS daily_history (
 day BIGINT PRIMARY KEY, net_sales_cents BIGINT NOT NULL, orders_count BIGINT NOT NULL,
 lost_sales BIGINT NOT NULL, cash_cents BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id),
 rating BIGINT NOT NULL CHECK(rating BETWEEN 1 AND 5), day BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS requests (
 scope TEXT NOT NULL, request_id TEXT NOT NULL, payload_hash TEXT NOT NULL, result TEXT NOT NULL,
 PRIMARY KEY(scope,request_id));
CREATE INDEX IF NOT EXISTS orders_by_customer ON orders(customer_id);
CREATE INDEX IF NOT EXISTS orders_by_status ON orders(status);
CREATE INDEX IF NOT EXISTS lines_by_order ON order_items(order_id);
CREATE INDEX IF NOT EXISTS payments_by_order ON payments(order_id);
CREATE INDEX IF NOT EXISTS inventory_by_product ON inventory_logs(product_id);
CREATE INDEX IF NOT EXISTS ledger_by_day ON ledger(day);
CREATE OR REPLACE VIEW order_summary AS
 SELECT o.id, c.name AS customer, o.status, o.payment_status, o.total_cents,
 o.created_day, COALESCE(SUM(i.quantity),0) AS units
 FROM orders o JOIN customers c ON c.id=o.customer_id LEFT JOIN order_items i ON i.order_id=o.id
 GROUP BY o.id,c.name,o.status,o.payment_status,o.total_cents,o.created_day;

COMMIT;
